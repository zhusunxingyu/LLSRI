def get_city_profile(city_name: str) -> CityProfile:
    return CITY_PROFILES.get(city_name, CITY_PROFILES["上海"])


def get_city_places(city_name: str) -> dict[str, tuple[float, float]]:
    places = {"自定义地点": (get_city_profile(city_name).lon, get_city_profile(city_name).lat)}
    places.update(CITY_PLACE_BOOK.get(city_name, CITY_PLACE_BOOK["上海"]))
    return places


def city_adjusted_zones(base_zones: pd.DataFrame, city_name: str) -> pd.DataFrame:
    city = get_city_profile(city_name)
    zones = base_zones.copy()
    lon_delta = city.lon - 121.4737
    lat_delta = city.lat - 31.2304
    zones["center_lon"] = zones["center_lon"] + lon_delta
    zones["center_lat"] = zones["center_lat"] + lat_delta
    zones["building_density"] = (zones["building_density"] * city.building_factor).clip(0, 1)
    zones["residential"] = (zones["residential"] * city.population_factor).clip(0, 1)
    zones["commercial"] = (zones["commercial"] * city.population_factor).clip(0, 1)
    zones["transport"] = (zones["transport"] * city.airspace_factor).clip(0, 1)
    zones["compliance"] = (zones["compliance"] * city.compliance_factor).clip(0, 1)
    zones["city"] = city.name
    zones["city_notes"] = city.notes
    return zones

